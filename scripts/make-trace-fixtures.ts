/*
 * Writes tests/fixtures/traces/*.json: labelled sample traces for the stroke matcher (CLAUDE.md §7.5,
 * §9). They are synthesised from Make Me a Hanzi medians with seeded jitter, not recorded by hand:
 *   correct   every stroke in order, small jitter            → 0 misses
 *   sloppy    big jitter, shifted and shrunk, still in order  → 0 misses
 *   reversed  the first stroke drawn backwards, then correct  → 1 miss
 *   order     the second stroke drawn first, then correct     → 1 miss, judged "order"
 * "order" is only written when the first two strokes start far apart (otherwise the sample would be
 * ambiguous for a human too). Replace or extend with recorded traces from real devices when available.
 */
import fs from 'node:fs';
import path from 'node:path';
import readline from 'node:readline';
import { rng } from '../lib/check/random';
import { resample, toScreen, type Point } from '../lib/zh/trace';
import { VENDOR } from './data-fetch';

export const FIXTURE_CHARS = [...'一二三人口大小中木水日月山上下你好我是不女子马天王明手心火田'];
const OUT = path.join(process.cwd(), 'tests', 'fixtures', 'traces');

function gauss(r: () => number) {
  // Box–Muller
  const u = Math.max(r(), 1e-9);
  return Math.sqrt(-2 * Math.log(u)) * Math.cos(2 * Math.PI * r());
}

function draw(median: Point[], r: () => number, opts: { sigma: number; dx: number; dy: number; scale?: number; reverse?: boolean }): Point[] {
  let pts = resample(median.map(toScreen), 24);
  if (opts.reverse) pts = [...pts].reverse();
  const cx = pts.reduce((s, p) => s + p[0], 0) / pts.length;
  const cy = pts.reduce((s, p) => s + p[1], 0) / pts.length;
  const sc = opts.scale ?? 1;
  // Hands wobble slowly over a stroke: noise at four control points, interpolated along it.
  const ctrl = Array.from({ length: 4 }, () => [gauss(r), gauss(r)]);
  const smooth = pts.map((_, i) => {
    const t = (i / (pts.length - 1)) * (ctrl.length - 1);
    const k = Math.min(Math.floor(t), ctrl.length - 2);
    const f = t - k;
    return [ctrl[k][0] * (1 - f) + ctrl[k + 1][0] * f, ctrl[k][1] * (1 - f) + ctrl[k + 1][1] * f];
  });
  return pts.map(([x, y], i) => [Math.round(cx + (x - cx) * sc + opts.dx + smooth[i][0] * opts.sigma), Math.round(cy + (y - cy) * sc + opts.dy + smooth[i][1] * opts.sigma)] as Point);
}

async function main() {
  const want = new Set(FIXTURE_CHARS);
  const data = new Map<string, Point[][]>();
  const rl = readline.createInterface({ input: fs.createReadStream(path.join(VENDOR, 'mmah', 'graphics.txt'), 'utf8'), crlfDelay: Infinity });
  for await (const line of rl) {
    const ch = /^\{"character":"(.)"/u.exec(line)?.[1];
    if (ch && want.has(ch)) data.set(ch, (JSON.parse(line) as { medians: Point[][] }).medians);
  }
  fs.mkdirSync(OUT, { recursive: true });
  let n = 0;
  for (const [ci, ch] of FIXTURE_CHARS.entries()) {
    const medians = data.get(ch);
    if (!medians) throw new Error(`no stroke data for ${ch}`);
    const r = rng(1000 + ci);
    const samples: { label: string; strokes: Point[][]; misses: number; firstMiss?: 'order' | 'shape' }[] = [];
    samples.push({ label: 'correct', strokes: medians.map((m) => draw(m, r, { sigma: 10, dx: 6, dy: -4 })), misses: 0 });
    samples.push({ label: 'sloppy', strokes: medians.map((m) => draw(m, r, { sigma: 22, dx: 40, dy: 30, scale: 0.88 })), misses: 0 });
    const s0 = resample(medians[0].map(toScreen), 8);
    if (Math.hypot(s0[7][0] - s0[0][0], s0[7][1] - s0[0][1]) > 250) {
      samples.push({
        label: 'reversed',
        strokes: [draw(medians[0], r, { sigma: 8, dx: 0, dy: 0, reverse: true }), ...medians.map((m) => draw(m, r, { sigma: 8, dx: 0, dy: 0 }))],
        misses: 1,
      });
    }
    if (medians.length >= 2) {
      const a = toScreen(medians[0][0]);
      const b = toScreen(medians[1][0]);
      if (Math.hypot(a[0] - b[0], a[1] - b[1]) > 0.3 * 1024) {
        samples.push({
          label: 'order',
          strokes: [draw(medians[1], r, { sigma: 8, dx: 0, dy: 0 }), ...medians.map((m) => draw(m, r, { sigma: 8, dx: 0, dy: 0 }))],
          misses: 1,
          firstMiss: 'order',
        });
      }
    }
    fs.writeFileSync(path.join(OUT, `${ch.codePointAt(0)!.toString(16)}.json`), `${JSON.stringify({ char: ch, medians, samples })}\n`);
    n += samples.length;
  }
  fs.writeFileSync(
    path.join(OUT, 'README.md'),
    '# Trace fixtures\n\nLabelled sample traces for `lib/zh/trace.ts`, one file per character (named by code point).\n' +
      'Generated by `npx tsx scripts/make-trace-fixtures.ts` from Make Me a Hanzi medians with seeded jitter,\n' +
      '**not recorded by hand**. See the script for the labels. Add traces recorded on phones and tablets\n' +
      '(as `samples` with the same shape) before tuning the thresholds further.\n',
  );
  console.log(`trace fixtures — ${FIXTURE_CHARS.length} characters, ${n} samples`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
